async function fetchJson(url, userAgent) {
	const ctrl = new AbortController();
	const timer = setTimeout(() => ctrl.abort(), FETCH_TIMEOUT_MS);
	try {
		const res = await fetch(url, {
			signal: ctrl.signal,
			headers: {
				"User-Agent": userAgent,
				Accept: "application/json"
			}
		});
		if (!res.ok) return null;
		const data = await res.json();
		return Array.isArray(data) ? data : null;
	} catch {
		return null;
	} finally {
		clearTimeout(timer);
	}
}
async function loadCatalog(now = /* @__PURE__ */ new Date()) {
	if (cache && now.getTime() - cache.at < CACHE_MS) return cache.payload;
	const cfg = getObjectsConfig();
	const wanted = new Set(cfg.objects.map((o) => o.norad));
	const merged = new Map(seedOmms);
	const results = await Promise.all(cfg.celestrak.queries.map((url) => fetchJson(url, cfg.userAgent)));
	let liveHits = 0;
	for (const list of results) {
		if (!list) continue;
		const idx = indexOmms(list);
		for (const [id, omm] of idx) {
			if (!wanted.has(id)) continue;
			merged.set(id, omm);
			liveHits += 1;
		}
	}
	const liveOk = liveHits > 0;
	const payload = buildCatalog({
		omms: merged,
		fetchedAt: liveOk ? now.toISOString() : seedFetchedAt,
		source: liveOk ? "live" : "seed",
		warning: liveOk ? null : "Live catalog fetch failed; using a checked-in public GP snapshot from 2026-09-20.",
		now
	});
	if (liveOk && payload.missingKnownIds.length > 0) payload.warning = `Known NORAD IDs missing from the public catalog: ${payload.missingKnownIds.join(", ")}.`;
	cache = {
		at: now.getTime(),
		payload
	};
	return payload;
}
